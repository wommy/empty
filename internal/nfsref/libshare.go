// Package nfsref is a reference model of the Linux NFS export chain the
// endpoint drives: OpenZFS libshare (sharenfs -> /etc/exports.d/zfs.exports),
// nfs-utils exportfs (exports files -> /var/lib/nfs/etab) and mountd's
// export lookup (etab -> what a client address is granted). Every function
// is derived line by line from the C sources; citations name the file and
// lines at these revisions:
//
//   - openzfs a128b8a (2.4 line): lib/libzfs/os/linux/libzfs_share_nfs.c
//     ("share_nfs.c"), lib/libzfs/libzfs_share_nfs.c ("libshare_nfs.c"),
//     lib/libzfs/libzfs_share.c, lib/libzfs/libzfs_dataset.c;
//   - nfs-utils 3.1.1 (5090e0b): support/nfs/exports.c, support/nfs/xio.c,
//     support/export/{export,client,xtab,hostname,cache,auth}.c,
//     utils/exportfs/exportfs.c.
//
// What the model cannot know is injected: name resolution (Resolver),
// realpath(3) and mountpoint checks. Behaviour that depends on libc or the
// kernel rather than on these sources is marked "ambiguity" and is what the
// real-nfsd replay (internal/endpoint nfs_replay_test.go) checks.
package nfsref

import (
	"errors"
	"fmt"
	"slices"
	"strings"
)

// ErrSyntax is libshare's SA_SYNTAX_ERR: `zfs set sharenfs=...` fails with
// "'sharenfs' cannot be set to invalid options".
var ErrSyntax = errors.New("SA_SYNTAX_ERR")

// ExportsHeader starts every zfs.exports file libzfs writes
// (libzfs_share.h:103 NFS_FILE_HEADER; libshare_nfs.c:233).
const ExportsHeader = "# !!! DO NOT EDIT THIS FILE MANUALLY !!!\n\n"

// ValidateSharenfs is the check `zfs set`/`zfs create -o` applies to a
// sharenfs value (libzfs_dataset.c:1229-1248): "on" and "off" pass; any
// other value goes through sa_validate_shareopts (libzfs_share.c:103-112),
// which refuses \a \b \f \n \r anywhere, then nfs_validate_shareopts
// (share_nfs.c:498-512): "" is refused, else the value must convert with
// get_linux_shareopts. Tab, \v and space are NOT refused.
func ValidateSharenfs(v string) error {
	if v == "on" || v == "off" {
		return nil
	}
	if strings.ContainsAny(v, "\a\b\f\n\r") {
		return ErrSyntax
	}
	if v == "" {
		return ErrSyntax
	}
	_, err := linuxShareopts(v)
	return err
}

// foreachShareopt is foreach_nfs_shareopt (share_nfs.c:51-109): "on" is
// "rw,crossmnt" (:61-62); options split on ','; empty options are skipped
// (:84 cur > opt); the key ends at the first '=' (:85-90), value nil when
// there is none.
func foreachShareopt(shareopts string, cb func(key string, value *string) error) error {
	if shareopts == "on" {
		shareopts = "rw,crossmnt"
	}
	for _, opt := range strings.Split(shareopts, ",") {
		if opt == "" {
			continue
		}
		var value *string
		if i := strings.IndexByte(opt, '='); i >= 0 {
			v := opt[i+1:]
			value, opt = &v, opt[:i]
		}
		if err := cb(opt, value); err != nil {
			return err
		}
	}
	return nil
}

// splitHosts walks a rw=/ro= host list like foreach_nfs_host_cb
// (share_nfs.c:151-207): hosts are separated by ':'; a host starting with
// '[' is an IPv6 literal, optionally followed by "/len". An empty list
// value is one empty host (no "*" substitution here: only a missing value,
// nil, becomes "*", :141-142).
func splitHosts(value string) ([]string, error) {
	var hosts []string
	host := value
	for {
		var next string
		more := false
		if strings.HasPrefix(host, "[") {
			host = host[1:]                     // :155
			end := strings.IndexByte(host, ']') // :156
			if end < 0 {
				return nil, ErrSyntax // :157-160
			}
			rest := host[end+1:]
			switch {
			case rest == "": // :161-163
				host = host[:end]
			case rest[0] == '/': // :164-180: drop ']' and keep "/len"
				if c := strings.IndexByte(rest[1:], ':'); c >= 0 {
					next, more = rest[1+c+1:], true
					host = host[:end] + rest[:1+c]
				} else {
					host = host[:end] + rest
				}
			case rest[0] == ':': // :181-183
				next, more = rest[1:], true
				host = host[:end]
			default:
				return nil, ErrSyntax // :184-187
			}
		} else if c := strings.IndexByte(host, ':'); c >= 0 { // :189-193
			next, more = host[c+1:], true
			host = host[:c]
		}
		hosts = append(hosts, host)
		if !more {
			return hosts, nil
		}
		host = next
	}
}

// validKeys is get_linux_shareopts_cb's sorted list (share_nfs.c:303-309).
var validKeys = []string{"all_squash", "anongid",
	"anonuid", "async", "auth_nlm", "crossmnt", "fsid", "fsuid", "hide",
	"insecure", "insecure_locks", "mountpoint", "mp", "no_acl",
	"no_all_squash", "no_auth_nlm", "no_root_squash",
	"no_subtree_check", "no_wdelay", "nohide", "refer", "replicas",
	"root_squash", "secure", "secure_locks", "subtree_check", "sync",
	"wdelay"}

// linuxShareopts is get_linux_shareopts (share_nfs.c:379-403) with its
// callback get_linux_shareopts_cb (:299-373): the option string appended
// to every host's access mode.
func linuxShareopts(shareopts string) (string, error) {
	opts := []string{"no_subtree_check", "mountpoint"} // :389, :392
	add := func(key string, value *string) {           // add_linux_shareopt :258-288
		if value != nil {
			opts = append(opts, key+"="+*value)
		} else {
			opts = append(opts, key)
		}
	}
	err := foreachShareopt(shareopts, func(key string, value *string) error {
		if key == "sec" { // :314-315
			return nil
		}
		if key == "ro" || key == "rw" { // :317-353: only the [v6] syntax is checked
			if value == nil || *value == "" {
				return nil
			}
			_, err := splitHosts(*value)
			return err
		}
		if key == "anon" { // :355-356
			key = "anonuid"
		}
		if key == "root_mapping" { // :358-361
			add("root_squash", nil)
			key = "anonuid"
		}
		if key == "nosub" { // :363-364
			key = "subtree_check"
		}
		if _, ok := slices.BinarySearch(validKeys, key); !ok { // :366-368
			return ErrSyntax
		}
		add(key, value)
		return nil
	})
	if err != nil {
		return "", err
	}
	return strings.Join(opts, ","), nil
}

// linuxHostspec is get_linux_hostspec (share_nfs.c:237-253): a leading '@'
// is dropped, so "@10.0.0.0/8" is the subnet, never a netgroup.
func linuxHostspec(h string) string {
	return strings.TrimPrefix(h, "@")
}

// EscapeMountpoint is nfs_escape_mountpoint (libshare_nfs.c:142-168):
// \t \n \v \f \r space and backslash become \ooo. '"' and '#' are not
// escaped.
func EscapeMountpoint(mp string) string {
	if !strings.ContainsAny(mp, "\t\n\v\f\r \\") {
		return mp
	}
	var b strings.Builder
	for i := 0; i < len(mp); i++ {
		if strings.IndexByte("\t\n\v\f\r \\", mp[i]) >= 0 {
			fmt.Fprintf(&b, "\\%03o", mp[i])
		} else {
			b.WriteByte(mp[i])
		}
	}
	return b.String()
}

// ExportsLines is what nfs_enable_share_impl (share_nfs.c:440-452) writes
// for one dataset: get_linux_shareopts first (an error writes nothing),
// then one nfs_add_entry line per host (:410-435):
//
//	<escaped mp> <host without '@'>(sec=<sec>,<rw|ro>,<linux opts>)\n
//
// sec starts as "sys" (:228) and each "sec" option changes it for the
// hosts after it (:137-138); a bare "sec" makes it NULL, which glibc's
// printf prints as "(null)" (ambiguity: libc). A missing rw/ro value is
// "*" (:141-142); an empty one is an empty host, written as
// "<mp> (sec=...)", which nfs-utils reads as "*" (exports.c:173-176).
func ExportsLines(mountpoint, sharenfs string) ([]string, error) {
	linuxOpts, err := linuxShareopts(sharenfs)
	if err != nil {
		return nil, err
	}
	mp := EscapeMountpoint(mountpoint)
	security := "sys"
	var lines []string
	err = foreachShareopt(sharenfs, func(key string, value *string) error {
		if key == "sec" {
			if value == nil {
				security = "(null)"
			} else {
				security = *value
			}
		}
		if key != "rw" && key != "ro" {
			return nil
		}
		v := "*"
		if value != nil {
			v = *value
		}
		hosts, err := splitHosts(v)
		if err != nil {
			return err
		}
		for _, h := range hosts {
			lines = append(lines, fmt.Sprintf("%s %s(sec=%s,%s,%s)\n", mp, linuxHostspec(h), security, key, linuxOpts))
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return lines, nil
}

// ShareFile is nfs_toggle_share (libshare_nfs.c:244-277) on a zfs.exports
// file: the header, every old line except comment and blank lines and
// except those of mountpoint (nfs_copy_entries, :170-242: a line belongs
// to mountpoint when its first field, up to a tab, space or newline, is
// the escaped mountpoint), then the new lines. sharenfs "off" (unshare,
// nfs_disable_share_impl :468-473) writes no new lines. On an error the
// file is left as it was (:273-276) and the error is returned.
func ShareFile(old, mountpoint, sharenfs string) (string, error) {
	var lines []string
	if sharenfs != "off" {
		var err error
		if err = ValidateSharenfs(sharenfs); err != nil { // sa_enable_share, libzfs_share.c:51-58
			return old, err
		}
		if lines, err = ExportsLines(mountpoint, sharenfs); err != nil {
			return old, err
		}
	}
	mp := EscapeMountpoint(mountpoint)
	var b strings.Builder
	b.WriteString(ExportsHeader)
	for _, line := range splitKeepNL(old) {
		if line[0] == '\n' || line[0] == '#' { // :192-193
			continue
		}
		sep := strings.IndexAny(line, "\t \n") // :196-198
		if sep == len(mp) && strings.HasPrefix(line, mp) {
			continue
		}
		b.WriteString(line)
	}
	for _, l := range lines {
		b.WriteString(l)
	}
	return b.String(), nil
}

// splitKeepNL splits like getline(3): each piece keeps its '\n'; a last
// piece without one is kept too.
func splitKeepNL(s string) []string {
	var out []string
	for s != "" {
		i := strings.IndexByte(s, '\n')
		if i < 0 {
			out = append(out, s)
			break
		}
		out = append(out, s[:i+1])
		s = s[i+1:]
	}
	return out
}
