#!/usr/bin/env bash
# CPU-seconds (user+sys; immune to the box's load) of build+link+start-up vs. running the tests, own packages changed, deps cached.
S=/tmp/claude-0/-home-user-empty/d2383434-1d2e-5ac5-931d-d25ccb26a882/scratchpad/wave10
export GOTOOLCHAIN=go1.27.3
cd "$S/wt-copy"
TIMEFORMAT="wall=%R user=%U sys=%S"
touchall() { for d in $(find . -name '*.go' -not -name '*_test.go' -printf '%h\n' | sort -u); do f=$(ls "$d"/*.go | grep -v _test.go | head -1); printf '\n// cpu-touch %s\n' "$1" >> "$f"; done; }
run() { echo -n "$1: " >> $S/cpu.txt; shift; { time "$@" >/dev/null 2>&1; } 2>> $S/cpu.txt; }
export GOCACHE=$S/gocache-ci2
touchall a
run "plain  build+link only (go test -c-equivalent: -run ^\$ -count=1), own changed" go test -count=1 -run '^$' ./...
run "plain  rerun, everything cached except test execution (-run ^\$)" go test -count=1 -run '^$' ./...
run "plain  full test run, warm" go test -count=1 ./...
export GOCACHE=$S/gocache-ci
touchall b
run "race   build+link only (-run ^\$), own changed" go test -race -count=1 -run '^$' ./...
run "race   rerun -run ^\$ (all cached; per-binary start+exit incl. 1s atexit sleep)" go test -race -count=1 -run '^$' ./...
run "race   full test run, warm" go test -race -count=1 ./...
run "race   full test run, warm, GORACE=atexit_sleep_ms=0" env GORACE=atexit_sleep_ms=0 go test -race -count=1 ./...
export GOCACHE=$S/gocache-ci2
run "vet    (plain cache warm, own changed a)" go vet ./...
echo done >> $S/cpu.txt
