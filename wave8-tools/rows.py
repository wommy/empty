#   drive   type | table | scenario -- what the residual test looks like (type = compile-time + one constructor test)
#   status  current | current-untested | open-finding | decided-pending
#             current          : HEAD 9f1790d does it and a test asserts it
#             current-untested : HEAD does it, no test asserts it
#             open-finding     : desired behaviour, HEAD violates it (adversary proof exists)
#             decided-pending  : owner/ADR decided, not implemented at HEAD
#   oracle  where the expected value must come from: openzfs | nfs-utils | csi-spec | adr | self
